from __future__ import annotations

import sys
from pathlib import Path

import typer

from slarti import __version__, docs, env, report, runner, scaffold, vocabulary
from slarti import config as config_module
from slarti.adapters.likec4 import AdapterError
from slarti.domain import Probe
from slarti.registry import RegistryError

app = typer.Typer(
    add_completion=False,
    no_args_is_help=True,
    help=(
        "Coordination CLI for validated architecture docs.\n"
        "\n"
        "slartiarch checks consistency between LikeC4 diagrams, LinkML schemas,\n"
        "and SHACL shapes. It owns the seams — the joins neither tool can see:\n"
        "  • Elements ↔ LinkML — the ownership seam (OWN-1..OWN-5)\n"
        "  • Document ↔ models  — the drift gate (DOC-1, DOC-3, DOC-4)\n"
        "  • Document ↔ rules  — the constraint registry (REG-1..REG-7)\n"
        "  • Instance inputs   — vocabulary instances any tool may produce (INP-1..INP-3)\n"
        "  • Mermaid diagrams  — sequence and ER diagrams read in Python (MMD-1..MMD-4)\n"
        "  • Diagrams ↔ elements — attachment, identity, dangling, drawn, kind\n"
        "    (ATTACH-*, IDENT-*, DANGLE-*, DRAWN-1, KIND-1)\n"
        "Everything else — parsing, validation, rendering — is delegated.\n"
        "\n"
        "Project layout (``slarti init`` scaffolds this):\n"
        "  docs/\n"
        "    architecture.md          prose with generated diagram and table regions\n"
        "    slarti/\n"
        "      likec4/*.c4            LikeC4 architecture model\n"
        "      linkml/*.yaml          LinkML domain schemas\n"
        "      shacl/*.ttl            hand-written SHACL shapes\n"
        "      constraints.yaml       rule registry\n"
        "      data/valid/*           fixtures that must pass\n"
        "      data/invalid/*         one fixture per SHACL rule; each must fail\n"
        "\n"
        "Regions between ``<!-- slarti:begin <name> -->`` and ``<!-- slarti:end <name> -->``\n"
        "are regenerated by ``slartiarch check --fix``. Hand edits to generated regions are\n"
        "reported as DOC-1 and block the merge.\n"
        "\n"
        "Commands:\n"
        "  init          scaffold a project (never overwrites)\n"
        "  doctor        resolve paths and probe tool versions\n"
        "  check         validate model sources against all rules (--fix regenerates regions)\n"
        "  report        every rule, shape, class, and check ID with remedy\n"
        "\n"
        "Typical workflow: init → doctor → check --fix → check, then report for details.\n"
        "Config: slarti.toml (preferred) or tool.slartiarch in pyproject.toml."
    ),
)

EXIT_CLEAN = 0
EXIT_FINDINGS = 1
EXIT_ENVIRONMENT = 2

DIRECTORY_ARGUMENT = typer.Argument(Path("."), help="Project root.")


def _load() -> config_module.Config:
    return _load_config()


def _mermaid_root(cfg: config_module.Config) -> Path | None:
    """The root whose pinned Mermaid is checked, when the Mermaid adapter runs."""
    return cfg.root if cfg.mermaid_enabled() else None


def _gate(cfg: config_module.Config) -> None:
    probes = env.probe_all(likec4=cfg.likec4_enabled(), mermaid=_mermaid_root(cfg))
    failures = env.env_findings(probes)
    if failures:
        for finding in failures:
            typer.secho(f"[{finding.id}] {finding.message}", fg="red", err=True)
        raise typer.Exit(EXIT_ENVIRONMENT)


def _context() -> runner.Context:
    cfg = _load()
    _gate(cfg)
    try:
        return runner.context(cfg)
    except (RegistryError, AdapterError) as exc:
        typer.secho(str(exc), fg="red", err=True)
        raise typer.Exit(EXIT_ENVIRONMENT) from exc


_PATH_DESCRIPTIONS: dict[str, str] = {
    "likec4": "LikeC4 architecture model sources (*.c4)",
    "linkml": "LinkML domain entity schemas (*.yaml)",
    "linkml_index": "Root schema file (optional; falls back to alphabetically-first *.yaml)",
    "shacl": "SHACL shape files (*.ttl)",
    "shacl_valid": "Fixtures that must pass SHACL validation",
    "shacl_invalid": "Fixtures that must violate rules (one per rule)",
    "constraints": "Rule registry connecting rules to enforcers",
    "documents": "Architecture documents to generate",
    "instances": "Vocabulary instance files or directories (*.yaml, *.yml, *.json)",
    "mermaid": "Mermaid diagrams: *.mmd files, Markdown files, or directories of either",
}


@app.command()
def init(directory: Path = DIRECTORY_ARGUMENT) -> None:
    """Scaffold config, docs/slarti/, and an architecture doc with example markers.
    Never overwrites existing files."""
    result = scaffold.init(directory)
    for name in result.written:
        typer.echo(f"created {name}")
    for name in result.skipped:
        typer.secho(f"kept    {name} (already exists)", fg="yellow")


def _load_config() -> config_module.Config:
    try:
        return config_module.load()
    except config_module.ConfigError as exc:
        typer.secho(str(exc), fg="red", err=True)
        raise typer.Exit(EXIT_ENVIRONMENT) from exc


def _show_paths(cfg: config_module.Config) -> None:
    typer.echo(f"root: {cfg.root}")
    for key, value in sorted(cfg.paths.items()):
        desc = _PATH_DESCRIPTIONS.get(key, "")
        typer.echo(f"  {key:16} {value:40} {desc}")
    lists = (("documents", cfg.documents), ("instances", cfg.instances), ("mermaid", cfg.mermaid))
    for key, values in lists:
        if values:
            typer.echo(f"  {key:16} {str(values):40} {_PATH_DESCRIPTIONS[key]}")


@app.command()
def doctor() -> None:
    """Show resolved project paths and probe every delegated tool."""
    cfg = _load_config()
    _show_paths(cfg)
    typer.echo("")
    probes = env.probe_all(mermaid=_mermaid_root(cfg))
    for probe in probes:
        typer.echo(_probe_line(probe))
        typer.echo(f"     {probe.detail}")
    typer.echo(f"ok   {'vocabulary':8} {vocabulary.version():10} {vocabulary.SCHEMA}")
    typer.echo(f"     import as '{vocabulary.IMPORT}' from a project schema")
    for name, profile in vocabulary.profile_versions().items():
        typer.echo(f"ok   {'profile':8} {profile:10} {vocabulary.PROFILES[name]}")
        typer.echo(f"     optional; import as '{name}' from a project schema")
    failed = any(not p.ok for p in probes)
    raise typer.Exit(EXIT_ENVIRONMENT if failed else EXIT_CLEAN)


def _probe_line(probe: Probe) -> str:
    mark = "ok  " if probe.ok else "FAIL"
    return f"{mark} {probe.tool:8} {(probe.version or '-'):10} {probe.location or '-'}"


@app.command()
def check(
    json_output: bool = typer.Option(False, "--json", help="Structured findings on stdout."),
    skip_docs: bool = typer.Option(False, "--no-docs", help="Skip the DOC-* checks."),
    fix: bool = typer.Option(False, "--fix", help="Regenerate stale document regions first."),
) -> None:
    """Validate model sources against all rules. Use --json.
    IDs: INP-*, MMD-*, OWN-*, ATTACH-*, IDENT-*, DANGLE-*, DRAWN-*, KIND-*, REG-*,
    DOC-*, ENV-*.

    Documents use HTML-comment markers to delimit generated regions:
      <!-- slarti:begin <name> -->
      ...
      <!-- slarti:end <name> -->

    ``--fix`` replaces every region wholesale (idempotent — safe to re-run), then
    checks. Unbalanced markers are DOC-3 and are never rewritten.

    Recognised marker names: diagram:<view>, ownership, constraints, unverified,
    linkml_erd (Entity Relationship diagram from the LinkML schema).
    ``linkml_erd`` accepts gen-erdiagram options appended with ``?``, e.g.
    ``<!-- slarti:begin linkml_erd?classes=Finding,Report&exclude_attributes=true -->``.
    Underscores in option names are converted to hyphens (``max_hops`` → ``--max-hops``)."""
    ctx = _fixed(_context()) if fix else _context()
    report, delegated_ok = runner.check(ctx, include_docs=not skip_docs)
    typer.echo(report.as_json_verbose() if json_output else report.as_text())
    failed = report.errors > 0 or not delegated_ok
    raise typer.Exit(EXIT_FINDINGS if failed else EXIT_CLEAN)


def _fixed(ctx: runner.Context) -> runner.Context:
    """Regenerate stale regions; a rewritten document moves the lines findings point at."""
    written = docs.write(ctx.config, ctx.constraints, ctx.models)
    for path in written:
        typer.echo(f"regenerated {ctx.config.rel(path)}", err=True)
    return _context() if written else ctx


@app.command(name="report")
def report_command(
    json_output: bool = typer.Option(False, "--json", help="The whole report, fully detailed."),
) -> None:
    """Rules from constraints.yaml, every shape, class, and check ID. Use --json for detail."""
    ctx = _context()
    result = report.build(ctx.models, ctx.constraints)
    typer.echo(result.as_json() if json_output else result.as_text())
    raise typer.Exit(EXIT_FINDINGS if result.orphaned else EXIT_CLEAN)


@app.callback(invoke_without_command=True)
def _version_callback(
    version: bool = typer.Option(False, "--version", help="Show version"),
) -> None:
    if version:
        typer.echo(f"slartiarch {__version__}")
        raise typer.Exit()


def main() -> None:
    sys.exit(app())


__all__ = ["app", "main"]
